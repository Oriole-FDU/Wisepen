#!/usr/bin/env bash
# =============================================================================
# scripts/middleware/jenkins.sh
# -----------------------------------------------------------------------------
# Jenkins 运维入口。
#
# 用法：
#   jenkins.sh reload
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"

# ──────────────────────────────────────────────────────────────────────────────
# 装载公共库
# ──────────────────────────────────────────────────────────────────────────────
# shellcheck source=lib/common.sh
. "$SCRIPT_DIR/lib/common.sh"
# shellcheck source=lib/jenkins.sh
. "$SCRIPT_DIR/lib/jenkins.sh"

# ──────────────────────────────────────────────────────────────────────────────
# 执行命令
# ──────────────────────────────────────────────────────────────────────────────
case "${1:-}" in
    reload)
        shift
        [ "$#" -eq 0 ] || { err "jenkins.sh reload 不接受额外参数: $*"; exit 1; }
        do_reload_jenkins
        ;;
    --help|-h|"")
        sed -n '/^# ====/,/^# ====/p' "$0" | sed 's/^# \{0,1\}//' | head -12
        [ "${1:-}" = "" ] && exit 1 || exit 0
        ;;
    *)
        err "未知命令: $1"
        exit 1
        ;;
esac
